import {execFile} from 'node:child_process';
import {promisify} from 'node:util';
const run=promisify(execFile);
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {readFileSync,writeFileSync} from 'node:fs';
const file='../renders/baya-prototype.mp4';
const probe=JSON.parse((await run('ffprobe',['-v','error','-show_streams','-show_format','-of','json',file],{encoding:'utf8'})).stdout);
const video=probe.streams.find(s=>s.codec_type==='video');
const audio=probe.streams.find(s=>s.codec_type==='audio');
assert.equal(video.codec_name,'h264');
assert.equal(video.width,1920); assert.equal(video.height,1080);
assert.equal(video.r_frame_rate,'30/1'); assert.equal(Number(video.nb_frames),420);
assert.equal(audio.codec_name,'aac'); assert.equal(Number(audio.sample_rate),48000);
assert.ok(Math.abs(Number(probe.format.duration)-14)<.1);
await run('ffmpeg',['-v','error','-i',file,'-f','null','-']);
const sha256=createHash('sha256').update(readFileSync(file)).digest('hex');
writeFileSync('../renders/verification.json',JSON.stringify({video:{width:video.width,height:video.height,frames:video.nb_frames,fps:video.r_frame_rate},audio:{codec:audio.codec_name,sampleRate:audio.sample_rate},duration:probe.format.duration,sha256,fullDecode:'passed'},null,2)+'\n');
console.log('PASS: 1080p, 420 frames, 30 fps, H.264/AAC, 48 kHz audio, full decode; SHA-256 '+sha256);
